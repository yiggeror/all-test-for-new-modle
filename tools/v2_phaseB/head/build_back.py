def E(a,b,x):
    h=max(0.0,min(1.0,(x-a)/(b-a)));return h*h*(3.0-2.0*h)

def channel(rows,index):
    zz=[r[0] for r in rows]; vv=[r[index] for r in rows]
    dd=[(vv[i+1]-vv[i])/(zz[i+1]-zz[i]) for i in range(len(zz)-1)]
    mm=[dd[0]]
    for i in range(1,len(zz)-1):
        if dd[i-1]*dd[i]<=0:mm.append(0.0);continue
        a=zz[i]-zz[i-1];b=zz[i+1]-zz[i]
        p=2*b+a;q=b+2*a;mm.append((p+q)/(p/dd[i-1]+q/dd[i]))
    mm.append(dd[-1])
    def calc(z):
        if z<=zz[0]:return vv[0]
        if z>=zz[-1]:return vv[-1]
        i=bisect.bisect_right(zz,z)-1;h=zz[i+1]-zz[i];t=(z-zz[i])/h
        return (2*t**3-3*t*t+1)*vv[i]+(t**3-2*t*t+t)*h*mm[i]+(-2*t**3+3*t*t)*vv[i+1]+(t**3-t*t)*h*mm[i+1]
    return calc

def srgb(rgb):
    def f(x):
        x=x/255
        return x/12.92 if x<=0.04045 else ((x+.055)/1.055)**2.4
    return tuple(map(f,rgb))+(1.0,)

