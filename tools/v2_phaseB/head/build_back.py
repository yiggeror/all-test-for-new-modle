def veil(coll,m):
    # The support is shorter and narrower than the outer hair. It is a
    # separate true foil, with softly irregular effective hem behind locks.
    wid=channel([(1.032,.105),(1.075,.119),(1.122,.143),(1.169,.149),(1.218,.143),
                 (1.268,.129),(1.319,.110),(1.376,.103),(1.426,.097),(1.468,.089),
                 (1.517,.068),(1.551,.048)],1)
    def f(t,u,v):
        root=1.548-.067*abs(u)**2.18+.003*u
        end=1.023+.072*abs(u)**1.7+.010*sin(u*6.1+.32)+.0061*sin(u*10.9)
        z=root+(end-root)*t
        base=wid(z);x=base*u+(.0067*sin(t*4.55)-.0015)*E(.13,.70,t)
        # Near the scalp it lies just under the silver coverage; from the
        # neck down it sits a measured margin safely behind the back.
        y=shell_y(x,z)-.003-.019*E(1.47,1.30,z)-.008*E(1.24,1.08,z)
        y+=.0068*max(0,1-u*u)+.0020*sin(5.7*u+5*t)*E(.2,.7,t)
        y+=v*(.00105+.0018*E(.0,.25,t)*(1-E(.94,1,t)))*(.78-.33*abs(u))
        return x,y,z
    o=closed_foil('Suzu Back · recessed cool-violet veil',coll,m,f,98,64)
    o['Hair layer']='INNER';o['suzu_hair_role']='back_inner';o['suzu_hair_phase']=-.022;o['uv_flow']='U across width, V=0 root to 1 tip';return o

