def cprofile(p):
    return p[0][0],p[-1][0],channel(p,1)
CAP_CURVES=[cprofile(p) for _,p in _CAP_SAMPLES]
def crown_y(x,z):
    if not CAP_CURVES:return shell_y(x,z)
    if z<CAP_ZS[0]:
        # Extend the measured local tangent below the available rays; no
        # angle-dependent branch when the tapered skull shell ends.
        zc=CAP_ZS[0];a=crown_y(x,zc);b=crown_y(x,zc+.005)
        slope=max(.08,min(.73,(b-a)/.005))
        return a+slope*(z-zc)
    i=max(0,min(len(CAP_CURVES)-2,bisect.bisect_right(CAP_ZS,z)-1))
    local=[]
    for j in range(max(0,i-1),min(len(CAP_CURVES),i+3)):
        lo,hi,curve=CAP_CURVES[j];zc=CAP_ZS[j]
        x1=max(lo,min(hi,x))
        d=curve(x1)
        if x1!=x:
            diff=d-shell_y(x1,zc);d=shell_y(x,zc)+diff*(1-E(0,.021,abs(x-x1)))
        local.append((zc,d))
    return channel(local,1)(z)

def closed_foil(name, coll, mat, point, steps, rings):
    """Closed sampled sections. Deliberate mirrored triangulation keeps each
       narrow bevel from crossing the adjacent face at a submillimetre tip."""
    assert rings%4==0
    top=rings//2
    verts=[];rows=[]
    # Y of HairUV tracks genuine arc length along the outer section apex.
    for i in range(steps+1):
        t=i/steps;rows.append(Vector(point(t,0.,1.)))
        for j in range(rings):
            ang=2*pi*j/rings
            # On the display side of the mesh the section runs left to right.
            verts.append(tuple(point(t,-sin(ang),-cos(ang))))
    lens=[0.0]
    for a,b in zip(rows,rows[1:]):lens.append(lens[-1]+(a-b).length)
    lens=[x/lens[-1] for x in lens]
    faces=[]
    # Mirror about the left/right side rails, using matching diagonals on
    # both material faces. Face orientation is adjusted by the real volume.
    def ix(i,k,side):return i*rings+((k+top//2 if side==0 else top//2-k)%rings)
    for k in range(top):
        for i in range(steps):
            for side in (0,1):
                a=ix(i,k,side);b=ix(i+1,k,side);c=ix(i+1,k+1,side);d=ix(i,k+1,side)
                ff=[(a,b,c),(a,c,d)]
                faces.extend(ff if side==0 else [tuple(reversed(f)) for f in ff])
    for i in (0,steps):
        for k in range(top):
            f=tuple(dict.fromkeys([ix(i,k,0),ix(i,k+1,0),ix(i,k+1,1),ix(i,k,1)]))
            faces.append(f if i==0 else tuple(reversed(f)))
    # Correct outward winding without a BMesh reorder (UV stations stay indexed).
    m=bpy.data.meshes.new(name);m.from_pydata(verts,[],faces);m.update();m.calc_loop_triangles()
    volume=sum(Vector(verts[a]).dot(Vector(verts[b]).cross(Vector(verts[c]))) for a,b,c in (t.vertices for t in m.loop_triangles))
    if volume<0:
        fs=[tuple(reversed(f)) for f in faces];bpy.data.meshes.remove(m);m=bpy.data.meshes.new(name);m.from_pydata(verts,[],fs);m.update()
    ob=bpy.data.objects.new(name,m);coll.objects.link(ob);m.materials.append(mat)
    uv=m.uv_layers.new(name='HairUV');m.uv_layers.active=uv;uv.active_render=True
    for p in m.polygons:
        p.use_smooth=True
        ids=[m.loops[j].vertex_index for j in p.loop_indices]
        for li,k in zip(p.loop_indices,ids):
            u=.5-.5*sin(2*pi*(k%rings)/rings)
            uv.data[li].uv=(u,lens[k//rings])
    for ed in m.edges:
        if all(k%rings==rings//4 for k in ed.vertices) or all(k%rings==3*rings//4 for k in ed.vertices):ed.use_seam=True
    ob['HairUV']='V 0 root / 1 tip by length; U 0 left / .5 ridge / 1 right on either face'
    return ob

