def smooth_profile(table,z):
    v=[r[0] for r in table]
    if z <= v[0]:return table[0][1:]
    if z >= v[-1]:return table[-1][1:]
    i=next(k for k in range(len(v)-1) if v[k]<=z<=v[k+1]);dt=v[i+1]-v[i]; t=(z-v[i])/dt
    def deriv(j,col):
        if j==0:return (table[1][col]-table[0][col])/(v[1]-v[0])
        if j==len(table)-1:return (table[-1][col]-table[-2][col])/(v[-1]-v[-2])
        l=(table[j][col]-table[j-1][col])/(v[j]-v[j-1]); r=(table[j+1][col]-table[j][col])/(v[j+1]-v[j])
        if l*r<=0:return 0.
        a=2*(v[j+1]-v[j])+v[j]-v[j-1]; b=v[j+1]-v[j]+2*(v[j]-v[j-1])
        return (a+b)/(a/l+b/r)
    return tuple((2*t*t*t-3*t*t+1)*table[i][col]+(t*t*t-2*t*t+t)*dt*deriv(i,col)+(-2*t*t*t+3*t*t)*table[i+1][col]+(t*t*t-t*t)*dt*deriv(i+1,col) for col in range(1,len(table[0])))
def gauss(x,s):return math.exp(-.5*(x/s)**2)
def leg_point(z,angle,side=1,allowance=0.0):
    x,y,rx,rf,rb=smooth_profile(LEG,z)
    c,s=math.cos(angle),math.sin(angle)
    # Medial femoral condyle, lateral gastrocnemius, patella and tibial crest.
    rx+=.0024*gauss(z-.455,.016)*max(-c,0)**3+.0016*gauss(z-.363,.034)*max(c,0)**4
    r=rf if s<0 else rb
    r+=.0031*gauss(z-.459,.014)*max(-s,0)**9+.0016*gauss(z-.315,.060)*max(-s,0)**18
    # Slightly softer anterior knee and a taper into the asymmetric ankle bones.
    rx+=.0017*gauss(z-.101,.009)*max(-c,0)**5+.0018*gauss(z-.091,.009)*max(c,0)**5
    return (side*(x+(rx+allowance)*c), y+(r+allowance)*s,z)
